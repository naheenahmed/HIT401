"""
analysis_report.py -- report-grade statistics and figures for the final report.

Run AFTER full_experiment.py (it reads the CSV files that script writes):

    python full_experiment.py
    python analysis_report.py

Outputs (written to ./report_outputs/):
    tables.json                 every number quoted in Section 5 of the report
    fig5_1_accuracy.png         accuracy by coordination structure (95% Wilson CI)
    fig5_2_team_size.png        accuracy by team size
    fig5_3_overhead.png         messages per task by team size
    fig5_4_efficiency.png       negotiation allocation efficiency by team size
    fig5_5_sensitivity.png      sensitivity of the decomposition result to the
                                assumed peer-to-peer error rate
    fig5_6_fix.png              accuracy before / after the two targeted fixes

Figures contain no embedded titles (captions are typeset in the report) and use
distinct markers, line styles and hatching so they remain readable in
black and white.

Method notes
------------
* Confidence intervals: Wilson score interval (Wilson, 1927), 95%.
* Paired significance test: exact McNemar test on tasks where the two
  conditions disagree (both conditions are run on the same task).
* Effect size: Cohen's h for two proportions (Cohen, 1988).
* Sensitivity: per-seed accuracies are regenerated by calling the same
  functions used in full_experiment.py, so per-seed values (not stored in the
  Stage 2 CSV) are available for a Welch t-test.
"""

import csv
import json
import math
import os
import random
import statistics as stats
from collections import Counter, defaultdict

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy import stats as sps

import full_experiment as fe   # re-uses task builders and agent policies

OUT = "report_outputs"
os.makedirs(OUT, exist_ok=True)

plt.rcParams.update({"font.size": 10, "figure.dpi": 200, "font.family": "serif"})
C_CEN, C_P2P, C_FIX = "#1F4E79", "#B03A2E", "#3B7D3B"


# ---------------------------------------------------------------- helpers
def wilson(k, n, z=1.96):
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    a = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return (c - a) / d, (c + a) / d


def cohens_h(p1, p2):
    return 2 * math.asin(math.sqrt(p1)) - 2 * math.asin(math.sqrt(p2))


def mcnemar_exact(a_correct, b_correct):
    """a_correct, b_correct: dict task_id -> bool (paired). Exact two-sided."""
    only_a = sum(1 for t in a_correct if a_correct[t] and not b_correct[t])
    only_b = sum(1 for t in a_correct if (not a_correct[t]) and b_correct[t])
    n = only_a + only_b
    if n == 0:
        return only_a, only_b, 1.0
    p = sps.binomtest(min(only_a, only_b), n, 0.5).pvalue
    return only_a, only_b, p


def load(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def is_true(v):
    return v in ("True", "1", "true", True)


raw = load("results_raw.csv")
fix = load("fix_comparison_raw.csv")
T = {}   # everything quoted in the report


# ------------------------------------------- 1. main accuracy + paired tests
T["main"] = {}
for fam in ("decomposition", "negotiation"):
    cen = {r["task_id"]: is_true(r["correct"]) for r in raw
           if r["family"] == fam and r["condition"] == "centralised"}
    p2p = {r["task_id"]: is_true(r["correct"]) for r in raw
           if r["family"] == fam and r["condition"] == "peer_to_peer"}
    n = len(cen)
    kc, kp = sum(cen.values()), sum(p2p.values())
    lo_c, hi_c = wilson(kc, n)
    lo_p, hi_p = wilson(kp, n)
    only_c, only_p, p = mcnemar_exact(cen, p2p)
    T["main"][fam] = {
        "n_tasks": n,
        "cen_correct": kc, "cen_acc": kc / n, "cen_ci": [lo_c, hi_c],
        "p2p_correct": kp, "p2p_acc": kp / n, "p2p_ci": [lo_p, hi_p],
        "gap_points": 100 * (kc - kp) / n,
        "cohens_h": cohens_h(kc / n, kp / n),
        "mcnemar_cen_only": only_c, "mcnemar_p2p_only": only_p, "mcnemar_p": p,
    }

# ------------------------------------------------------ 2. by team size
T["by_size"] = {}
for fam in ("decomposition", "negotiation"):
    for cond in ("centralised", "peer_to_peer"):
        for k in (2, 3, 4, 5):
            rs = [r for r in raw if r["family"] == fam and r["condition"] == cond
                  and int(r["agent_count"]) == k]
            n = len(rs)
            kk = sum(is_true(r["correct"]) for r in rs)
            T["by_size"][f"{fam}|{cond}|{k}"] = {
                "n": n, "acc": kk / n,
                "msgs": stats.mean(float(r["n_messages"]) for r in rs),
                "turns": stats.mean(float(r["n_turns"]) for r in rs),
                "tokens": stats.mean(float(r["n_tokens"]) for r in rs),
                "msgs_per_agent": stats.mean(float(r["n_messages"]) for r in rs) / k,
                "eff": (stats.mean(float(r["efficiency"]) for r in rs)
                        if fam == "negotiation" else None),
            }

# overall communication cost by family/condition
T["overhead"] = {}
for fam in ("decomposition", "negotiation"):
    for cond in ("centralised", "peer_to_peer"):
        rs = [r for r in raw if r["family"] == fam and r["condition"] == cond]
        T["overhead"][f"{fam}|{cond}"] = {
            "msgs": stats.mean(float(r["n_messages"]) for r in rs),
            "turns": stats.mean(float(r["n_turns"]) for r in rs),
            "tokens": stats.mean(float(r["n_tokens"]) for r in rs),
            "wall_ms": 1000 * stats.mean(float(r["wall_time"]) for r in rs),
        }
rs = [r for r in raw if r["family"] == "negotiation"]
for cond in ("centralised", "peer_to_peer"):
    e = [float(r["efficiency"]) for r in rs if r["condition"] == cond]
    T["overhead"][f"negotiation_efficiency|{cond}"] = {
        "mean": stats.mean(e), "min": min(e), "sd": stats.stdev(e)}

# failure taxonomy (main run)
T["failures_main"] = {}
for fam in ("decomposition", "negotiation"):
    for cond in ("centralised", "peer_to_peer"):
        c = Counter(r["failure_tag"] for r in raw if r["family"] == fam
                    and r["condition"] == cond and r["failure_tag"])
        T["failures_main"][f"{fam}|{cond}"] = dict(c)

# ------------------------------------------------------ 3. sensitivity
decomp_tasks = fe.build_gsm8k_chain_tasks(per_bucket=15, seed=32)
per_seed = {}
for ratio in fe.ERROR_RATIOS:
    c_accs, p_accs = [], []
    for seed in fe.SEEDS:
        rng = random.Random(seed)
        c = sum(fe._run_chain_for_sensitivity(t, rng, fe.CENTRALISED_ERROR_RATE)
                for t in decomp_tasks) / len(decomp_tasks)
        p = sum(fe._run_chain_for_sensitivity(t, rng, fe.CENTRALISED_ERROR_RATE * ratio)
                for t in decomp_tasks) / len(decomp_tasks)
        c_accs.append(c)
        p_accs.append(p)
    t_stat, t_p = sps.ttest_ind(c_accs, p_accs, equal_var=False)
    per_seed[ratio] = {
        "p2p_rate": fe.CENTRALISED_ERROR_RATE * ratio,
        "cen_mean": stats.mean(c_accs), "cen_sd": stats.stdev(c_accs),
        "p2p_mean": stats.mean(p_accs), "p2p_sd": stats.stdev(p_accs),
        "gap": stats.mean(c_accs) - stats.mean(p_accs),
        "welch_p": float(t_p),
    }
T["sensitivity"] = {str(k): v for k, v in per_seed.items()}

seed_rows = load("sensitivity_seeds.csv")
T["seed_stability"] = {f"{r['family']}|{r['condition']}": {
    "mean": float(r["accuracy_mean"]), "sd": float(r["accuracy_std"]),
    "min": float(r["accuracy_min"]), "max": float(r["accuracy_max"])} for r in seed_rows}

# ------------------------------------------------------ 4. fix comparison
T["fix"] = {}
for fam in ("decomposition", "negotiation"):
    d = {}
    for cond in ("centralised", "peer_to_peer_BEFORE", "peer_to_peer_AFTER"):
        rs = [r for r in fix if r["family"] == fam and r["condition"] == cond]
        n = len(rs)
        k = sum(is_true(r["correct"]) for r in rs)
        lo, hi = wilson(k, n)
        d[cond] = {"n": n, "k": k, "acc": k / n, "ci": [lo, hi],
                   "msgs": stats.mean(float(r["n_messages"]) for r in rs),
                   "tokens": stats.mean(float(r["n_tokens"]) for r in rs),
                   "failures": dict(Counter(r["failure_tag"] for r in rs if r["failure_tag"]))}
    def paired(a, b):
        A = {r["task_id"]: is_true(r["correct"]) for r in fix if r["family"] == fam and r["condition"] == a}
        B = {r["task_id"]: is_true(r["correct"]) for r in fix if r["family"] == fam and r["condition"] == b}
        return mcnemar_exact(A, B)
    d["mcnemar_before_after"] = paired("peer_to_peer_BEFORE", "peer_to_peer_AFTER")
    d["mcnemar_cen_after"] = paired("centralised", "peer_to_peer_AFTER")
    T["fix"][fam] = d

with open(os.path.join(OUT, "tables.json"), "w") as f:
    json.dump(T, f, indent=2, default=float)


# ------------------------------------------- 5. efficiency-threshold check
# Does the negotiation result depend on the 0.90 "success" cut-off?  Uses the
# allocation-efficiency value only (convergence is ignored here).
T["threshold"] = {}
for thr in (0.70, 0.80, 0.90, 0.95):
    row = {}
    for cond in ("centralised", "peer_to_peer"):
        e = [float(r["efficiency"]) for r in raw
             if r["family"] == "negotiation" and r["condition"] == cond]
        row[cond] = sum(v >= thr for v in e) / len(e)
    T["threshold"][str(thr)] = row

with open(os.path.join(OUT, "tables.json"), "w") as f:
    json.dump(T, f, indent=2, default=float)

